<?php

use App\Models\Service;
use App\Models\User;
use Illuminate\Foundation\Testing\RefreshDatabase;

uses(RefreshDatabase::class);

/**
 * The red asterisk beside a label the backend will refuse empty.
 *
 * Two things are pinned here, and the second is the one that will actually
 * catch a regression.
 *
 * One: the marker reaches all three form idioms in this project — the
 * <x-input-label> Blade component on the auth and profile pages, Bootstrap's
 * .form-label on the public pages, and the admin panel's own .form-label.
 * They look nothing alike in markup and used to mark required fields three
 * different ways, or not at all.
 *
 * Two: a label is marked ONLY where the rule says `required`. An asterisk on a
 * field the server accepts empty is worse than no asterisk at all — it is the
 * form telling the customer something untrue — so each case below asserts the
 * absence as firmly as the presence. `notes` is the canonical optional field:
 * every booking path validates it `nullable`.
 *
 * Deliberately asserting the class on the <label>, not the rendered asterisk.
 * The asterisk is generated by `.required::after` in design-tokens.css and
 * never appears in the HTML, which is the whole point of doing it in CSS —
 * there is no per-label span to forget.
 */

/** The class attribute of the <label> whose text is exactly $text, or null. */
function labelClasses(string $html, string $text): ?string
{
    // Non-greedy over attributes, and the text has to be the label's whole
    // content: matching a substring would let "Notes" find "Additional Notes"
    // and report the wrong field's markup.
    $quoted = preg_quote($text, '~');

    if (! preg_match('~<label([^>]*)>\s*'.$quoted.'\s*</label>~', $html, $m)) {
        return null;
    }

    preg_match('~class="([^"]*)"~', $m[1], $c);

    return $c[1] ?? '';
}

function labelIsMarked(string $html, string $text): bool
{
    $classes = labelClasses($html, $text);

    expect($classes)->not->toBeNull("no <label> with the exact text \"{$text}\" was rendered");

    return in_array('required', preg_split('~\s+~', trim($classes)), true);
}

it('defines the marker once, in the stylesheet every layout loads', function () {
    // One rule, not a copy in the admin stylesheet and another in the public
    // one. design-tokens.css is loaded by the admin layout, the auth pages,
    // the customer dashboard, the landing page and both Breeze layouts, so
    // this is the only file that reaches all three form idioms.
    $css = file_get_contents(public_path('assets/css/design-tokens.css'));

    expect($css)->toContain('.required::after')
        ->and($css)->toContain('var(--red');

    // No new hex: the marker uses the existing token.
    expect($css)->toMatch('~\.required::after\s*\{[^}]*content:\s*\x27 \*\x27~');
});

it('marks a required field on the registration form and leaves the optional one alone', function () {
    $html = $this->get('/register')->assertOk()->getContent();

    // first_name, last_name, email and password are all `required` in
    // RegisteredUserController. phone is `nullable`.
    expect(labelIsMarked($html, 'First Name'))->toBeTrue();
    expect(labelIsMarked($html, 'Email Address'))->toBeTrue();
    expect(labelIsMarked($html, 'Phone Number'))->toBeFalse();
});

it('keeps the required attribute on the input, so the asterisk is not the only signal', function () {
    $html = $this->get('/register')->assertOk()->getContent();

    // What assistive technology actually announces, and what stops the
    // browser submitting an empty field. A generated asterisk cannot carry
    // aria-hidden, so this is what carries the meaning.
    expect($html)->toMatch('~name="first_name"[^>]*required~');
    expect($html)->not->toMatch('~name="phone"[^>]*required~');
});

it('marks a required field on the admin booking form and leaves the optional one alone', function () {
    Service::create([
        'name' => 'Change Oil (Gasoline)', 'description' => 'Oil and filter.',
        'price' => 1500, 'duration' => 45, 'category' => 'Engine & Oil', 'is_active' => true,
    ]);

    $html = $this->actingAs(User::factory()->create(['role' => 'admin']))
        ->get('/admin/bookings/create')
        ->assertOk()
        ->getContent();

    // service_ids, booking_date, booking_time, customer_name, customer_phone
    // and plate are `required` in BookingController::store(). notes,
    // mechanic_id, customer_email and the make/model/year fields are not.
    expect(labelIsMarked($html, 'Services'))->toBeTrue();
    expect(labelIsMarked($html, 'Full Name'))->toBeTrue();
    expect(labelIsMarked($html, 'Additional Notes'))->toBeFalse();
    expect(labelIsMarked($html, 'Assigned Mechanic'))->toBeFalse();
    expect(labelIsMarked($html, 'Email Address'))->toBeFalse();
});

it('marks a required field in the public booking modal and leaves the optional one alone', function () {
    Service::create([
        'name' => 'Change Oil (Gasoline)', 'description' => 'Oil and filter.',
        'price' => 1500, 'duration' => 45, 'category' => 'Engine & Oil', 'is_active' => true,
    ]);

    $html = $this->get('/')->assertOk()->getContent();

    // guest_name, guest_email, vehicle_make, vehicle_model, vehicle_year and
    // vehicle_plate are `required` in GuestBookingController. notes is not —
    // and neither is guest_phone, which that controller does not validate at
    // all.
    expect(labelIsMarked($html, 'Full name'))->toBeTrue();
    expect(labelIsMarked($html, 'Plate number'))->toBeTrue();
    expect(labelIsMarked($html, 'Notes / special request'))->toBeFalse();
    expect(labelIsMarked($html, 'Phone'))->toBeFalse();
});

it('renders the component marker as decoration, hidden from a screen reader', function () {
    // The <x-input-label required> path. Here the markup is written once in
    // one file, so the span can carry aria-hidden — which the CSS pseudo
    // element on a plain <label> cannot.
    $html = $this->actingAs(User::factory()->create(['role' => 'customer']))
        ->get('/profile')
        ->assertOk()
        ->getContent();

    expect($html)->toContain('<span class="required-mark" aria-hidden="true">');

    // And the field it marks still carries `required` itself.
    expect($html)->toMatch('~name="name"[^>]*required~');
});

it('leaves no hand-rolled asterisk behind', function () {
    // Six labels used to carry their own inline <span style="color:var(--red)">*</span>,
    // which is the thing the shared class replaces. A new one would mean the
    // mechanism had been forgotten again.
    $offenders = [];

    $files = new RecursiveIteratorIterator(
        new RecursiveDirectoryIterator(resource_path('views'))
    );

    foreach ($files as $file) {
        if ($file->isDir() || ! str_ends_with($file->getFilename(), '.blade.php')) {
            continue;
        }

        $source = file_get_contents($file->getPathname());

        // An asterisk inside a span carrying a colour. The component's own
        // marker is excluded by name, because that one IS the mechanism.
        if (preg_match('~<span[^>]*color:[^>]*>\s*\*\s*</span>~', $source)) {
            $offenders[] = str_replace(resource_path('views').DIRECTORY_SEPARATOR, '', $file->getPathname());
        }
    }

    expect($offenders)->toBe([]);
});
